#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
converter.py
------------
Collects YOLO detection results and converts them into a unified JSON file.
"""

import json
from pathlib import Path
from typing import Any, Dict, List, Tuple, Optional

from utils.logging import get_logger


class YOLOConverter:
    """
    Collect and organize YOLO detection results into a unified JSON dataset.
    """

    IMG_EXTS = (".jpg", ".jpeg", ".png", ".bmp")

    def __init__(self, config: Dict[str, Any]):
        self.logger = get_logger("yolo_cropper.YOLOConverter")

        self.cfg = config
        global_main_cfg = self.cfg.get("main", {})
        self.yolo_cropper_cfg = self.cfg.get("yolo_cropper", {})
        self.main_cfg = self.yolo_cropper_cfg.get("main", {})
        self.dataset_cfg = self.yolo_cropper_cfg.get("dataset", {})

        # Classes / categories from config (also used as subset candidates)
        self.categories: List[str] = global_main_cfg.get("categories", [])
        if not self.categories:
            raise ValueError("main.categories must be defined in config.yaml for YOLOConverter")
        self.num_classes = len(self.categories)

        # Subset candidates (for split-run dirs like yolov8m_repair / yolov5_replace)
        # Use config-defined categories for extensibility.
        self.known_subsets = set([c.lower() for c in self.categories])

        self.model_name = (
            self.yolo_cropper_cfg.get("main", {})
            .get("model_name", "yolov5")
            .lower()
        )

        self.detect_root = Path(self.dataset_cfg.get("detect_dir", "runs/detect")).resolve()
        self.results_root = Path(self.dataset_cfg.get("results_dir", "outputs/json_results")).resolve()
        self.output_json = self.results_root / self.model_name / "result.json"
        self.data_root = Path(self.main_cfg.get("input_dir", "data/original")).resolve()

        self.logger.info(f"Initialized YOLOConverter ({self.model_name.upper()})")
        self.logger.debug(f" - Detect Root : {self.detect_root}")
        self.logger.debug(f" - Results Root: {self.results_root}")
        self.logger.debug(f" - Output JSON : {self.output_json}")
        self.logger.debug(f" - Data Root   : {self.data_root}")

    # --------------------------------------------------------
    def _predict_list_path(self) -> Path:
        """
        predict.txt is expected to be generated by YOLOPredictListGenerator under:
          outputs/json_results/<model_name>/predict.txt
        """
        return (self.results_root / self.model_name / "predict.txt").resolve()

    def _index_predict_list(self, log_collisions: bool = True) -> Dict[str, List[Path]]:
        """
        Build mapping from image stem to list of absolute image paths from predict.txt.
        This preserves disambiguation when filenames collide across subsets.
        """
        p = self._predict_list_path()
        idx: Dict[str, List[Path]] = {}

        if not p.exists():
            self.logger.warning(f"[WARN] predict.txt not found: {p}")
            return idx

        with open(p, "r", encoding="utf-8") as f:
            for ln in f:
                s = ln.strip()
                if not s:
                    continue
                ip = Path(s).resolve()
                idx.setdefault(ip.stem, []).append(ip)

        collisions = {k: v for k, v in idx.items() if len(v) > 1}
        if log_collisions and collisions:
            self.logger.warning(
                f"[WARN] Detected {len(collisions)} filename collisions in predict.txt "
                f"(same stem appears multiple times)."
            )
            for k, v in list(collisions.items())[:5]:
                self.logger.warning(f"       - stem='{k}': {len(v)} candidates")

        return idx

    # --------------------------------------------------------
    def _resolve_detect_dirs(self) -> List[Path]:
        """
        Resolve detection directories corresponding to the current YOLO model.

        Rules:
        - YOLOv2 / YOLOv4 : exact directory match
        - YOLOv5          : multiple outputs (prefix match: yolov5_*)
        - YOLOv8{s,m,l,x}: match 'yolov8s' OR split-runs 'yolov8s_*'
        """
        if not self.detect_root.exists():
            return []

        all_dirs = [
            d for d in self.detect_root.iterdir()
            if d.is_dir() and (d / "labels").exists()
        ]

        model = self.model_name.lower()

        # YOLOv5 variants
        if model.startswith("yolov5"):
            return [d for d in all_dirs if d.name.startswith("yolov5")]

        # YOLOv8 variants (support split-run: yolov8m_repair, yolov8m_replace, ...)
        if model.startswith("yolov8"):
            return [d for d in all_dirs if (d.name == model or d.name.startswith(f"{model}_"))]

        # YOLOv2 / YOLOv4 variants
        return [d for d in all_dirs if d.name == model]

    # --------------------------------------------------------
    def _infer_subset_from_detect_dir(self, detect_dir: Path) -> Optional[str]:
        """
        Infer subset token from detect directory name.

        Supports:
          - yolov5_<subset>
          - yolov8s_<subset>, yolov8m_<subset>, ...
        Subset candidates come from config main.categories for extensibility.
        """
        name = detect_dir.name.lower()
        if "_" not in name:
            return None

        suffix = name.rsplit("_", 1)[-1]
        if suffix in self.known_subsets:
            return suffix
        return None

    # --------------------------------------------------------
    def _find_original_image(
        self,
        subset: Optional[str],
        stem: str,
        predict_index: Dict[str, List[Path]],
    ) -> Optional[Path]:
        # (1) subset-scoped lookup (best when subset is known)
        if subset:
            subset_dir = self.data_root / subset
            if subset_dir.exists():
                for ext in self.IMG_EXTS:
                    p = subset_dir / f"{stem}{ext}"
                    if p.exists():
                        return p.resolve()

        # (2) predict list mapping (only safe when unique)
        if predict_index:
            cands = [p for p in predict_index.get(stem, []) if p.exists()]
            if len(cands) == 1:
                return cands[0].resolve()
            if len(cands) > 1:
                self.logger.warning(
                    f"[WARN] Ambiguous original image for stem='{stem}' "
                    f"({len(cands)} candidates in predict.txt). Skipping."
                )
                return None

        # (3) global unique match under data_root
        matches: List[Path] = []
        for ext in self.IMG_EXTS:
            matches.extend(self.data_root.rglob(f"{stem}{ext}"))
        matches = [m.resolve() for m in matches if m.exists()]

        if len(matches) == 1:
            return matches[0]

        return None

    # --------------------------------------------------------
    def _parse_detect_folder(
        self,
        detect_dir: Path,
        frame_start: int,
        predict_index: Dict[str, List[Path]],
    ) -> Tuple[List[Dict[str, Any]], int]:
        """Parse YOLO label files inside a detection folder."""
        label_dir = detect_dir / "labels"
        if not label_dir.exists():
            self.logger.warning(f"[SKIP] {detect_dir} (no labels/)")
            return [], frame_start

        results: List[Dict[str, Any]] = []
        frame_id = frame_start

        subset = self._infer_subset_from_detect_dir(detect_dir)

        for label_file in sorted(label_dir.glob("*.txt")):
            with open(label_file, "r", encoding="utf-8") as f:
                lines = [ln.strip() for ln in f if ln.strip()]

            stem = label_file.stem
            orig_path = self._find_original_image(subset=subset, stem=stem, predict_index=predict_index)

            if orig_path is None or not orig_path.exists():
                self.logger.warning(
                    f"[WARN] Original image not found/ambiguous for label: {stem} (subset={subset})"
                )
                continue

            objects: List[Dict[str, Any]] = []
            for ln in lines:
                parts = ln.split()
                if len(parts) not in (5, 6):
                    continue

                cls_id = int(parts[0])
                if cls_id < 0 or cls_id >= self.num_classes:
                    self.logger.warning(f"[WARN] Invalid class_id {cls_id} in {label_file.name}")
                    continue

                x, y, w, h = map(float, parts[1:5])
                conf = float(parts[5]) if len(parts) == 6 else None

                objects.append(
                    {
                        "class_id": cls_id,
                        "name": self.categories[cls_id],
                        "relative_coordinates": {
                            "center_x": x,
                            "center_y": y,
                            "width": w,
                            "height": h,
                        },
                        "confidence": conf,
                    }
                )

            results.append(
                {
                    "frame_id": frame_id,
                    "filename": str(orig_path.resolve()),
                    "objects": objects,
                }
            )
            frame_id += 1

        self.logger.info(f"[+] Parsed {detect_dir.name} → {len(results)} frames")
        return results, frame_id

    # --------------------------------------------------------
    def run(self):
        """
        Collect YOLO detection outputs corresponding to the current model only.
        """
        detect_dirs = self._resolve_detect_dirs()

        if not detect_dirs:
            raise FileNotFoundError(f"No detection folders found for model: {self.model_name}")

        self.logger.info(
            f"[YOLOConverter] Found {len(detect_dirs)} detection folders for {self.model_name}:"
        )
        for d in detect_dirs:
            self.logger.info(f" - {d.name}")

        has_subset_dirs = any(self._infer_subset_from_detect_dir(d) is not None for d in detect_dirs)

        predict_index = self._index_predict_list(log_collisions=not has_subset_dirs)

        all_results: List[Dict[str, Any]] = []
        frame_id = 1

        for detect_dir in detect_dirs:
            results, frame_id = self._parse_detect_folder(
                detect_dir, frame_start=frame_id, predict_index=predict_index
            )
            all_results.extend(results)

        # ---- Save JSON ----
        self.output_json.parent.mkdir(parents=True, exist_ok=True)
        with open(self.output_json, "w", encoding="utf-8") as f:
            json.dump(all_results, f, ensure_ascii=False, indent=4)

        self.logger.info(f"[DONE] Detection results saved → {self.output_json}")
        self.logger.info(f" - Total frames: {len(all_results)}")
